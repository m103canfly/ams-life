// Builds the brain map page: src/brain.js + the vendored Galaxy View renderer
// (src/galaxy/, MIT) + three.js and d3-force-3d -> pages/brain/brain.bundle.js,
// one local file, nothing loaded from the network. Also copies the license of
// every package that ends up in the bundle into pages/brain/licenses/.
//
//   cd tools/brain
//   npm ci --ignore-scripts
//   node build.mjs
import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const page = path.resolve(here, '../../pages/brain');
const licenses = path.join(page, 'licenses');

// 'worker:' imports are bundled on their own and inlined as text (Blob URL worker),
// as in Galaxy View's esbuild.config.mjs.
const inlineWorker = {
	name: 'inline-worker',
	setup(build) {
		build.onResolve({ filter: /^worker:/ }, (args) => ({
			path: path.resolve(path.dirname(args.importer), args.path.slice('worker:'.length)),
			namespace: 'inline-worker',
		}));
		build.onLoad({ filter: /.*/, namespace: 'inline-worker' }, async (args) => {
			const result = await esbuild.build({
				entryPoints: [args.path], bundle: true, write: false, format: 'iife',
				target: 'es2021', minify: true, legalComments: 'none', metafile: true,
			});
			for (const input of Object.keys(result.metafile.inputs)) workerInputs.add(path.resolve(input));
			return { contents: result.outputFiles[0].text, loader: 'text' };
		});
	},
};
const workerInputs = new Set();

const result = await esbuild.build({
	entryPoints: [path.join(here, 'src/brain.js')],
	bundle: true,
	format: 'iife',
	target: 'es2021',
	minify: true,
	charset: 'utf8',
	legalComments: 'eof',   // keep the libraries' own @license notices
	define: { __GALAXY_DEV__: 'false' },
	banner: { js: '/* ams-life brain map (AGPL-3.0). Built by tools/brain/build.mjs; source in tools/brain/src/. Third-party licenses: licenses/. */' },
	outfile: path.join(page, 'brain.bundle.js'),
	metafile: true,
	plugins: [inlineWorker],
	logLevel: 'info',
});

// Every npm package in the bundle (main thread and worker), plus Galaxy View itself.
const inputs = new Set([...Object.keys(result.metafile.inputs).map((p) => path.resolve(p)), ...workerInputs]);
const packages = new Map();
for (const file of inputs) {
	const m = file.split(path.sep).join('/').match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
	if (!m) continue;
	const dir = file.slice(0, file.split(path.sep).join('/').indexOf(m[0]) + m[0].length);
	packages.set(m[1], dir);
}
fs.rmSync(licenses, { recursive: true, force: true });
fs.mkdirSync(licenses, { recursive: true });
const rows = [];
const copyLicense = (name, dir, version, license) => {
	const file = fs.readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));
	if (!file) throw new Error(`no license file in ${name}`);
	fs.copyFileSync(path.join(dir, file), path.join(licenses, name.replace('/', '__') + '.LICENSE.txt'));
	rows.push(`| ${name} | ${version} | ${license} |`);
};
for (const [name, dir] of [...packages].sort()) {
	const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
	copyLicense(name, dir, pkg.version, pkg.license);
}
copyLicense('galaxy-view', path.join(here, 'src/galaxy'), '0.6.1 (b49b60c)', 'MIT');
fs.writeFileSync(path.join(licenses, 'README.md'),
	'# Third-party code in brain.bundle.js\n\n' +
	'Generated by tools/brain/build.mjs. Each package\'s license text is in this folder.\n\n' +
	'| Package | Version | License |\n| --- | --- | --- |\n' + rows.join('\n') + '\n');
console.log('licenses:', rows.length);
